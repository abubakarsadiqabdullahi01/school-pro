// Builds one SQL file that turns a database into a release-ready schema.
//
// Why this exists: the cPanel account has **no terminal**. The only ways in are
// phpMyAdmin and Setup Node.js App's "Run JS script", which can run only the
// scripts already listed in the deployed package.json. `prisma migrate deploy`
// needs the Prisma CLI, which is a devDependency and deliberately not in the
// bundle — so the documented path (run it locally against remote MySQL) needs the
// host to whitelist an IP, and that is not always available.
//
// This produces a single file for phpMyAdmin's Import tab. It contains:
//
//   1. the whole schema, exactly as applying all migrations in order would leave
//      it — generated by Prisma itself from schema.prisma, not hand-written;
//   2. the `_prisma_migrations` table and one row per migration, marked applied
//      with the real checksum.
//
// Point 2 is what keeps this honest. Without it the database has the right tables
// but no history, and the next `prisma migrate deploy` would try to apply all the
// migrations over a populated schema and fail. The checksum is a plain sha256 of
// the migration file's bytes — verified against a database Prisma itself migrated.
//
// Usage:
//   npm run build:release-sql -- digisof1_schoolpro
//   npm run build:release-sql -- digisof1_schoolpro --reset   (drops first — deletes data)
//   npm run build:release-sql -- digisof1_schoolpro --upgrade-from <last applied migration>
//
// `--upgrade-from` is for a database that already holds real data. It writes only the
// migrations after the named one, each guarded (see upgradeFile below), and drops nothing.

import { execSync } from "node:child_process"
import crypto from "node:crypto"
import fs from "node:fs"
import path from "node:path"

const root = process.cwd()
const migrationsDir = path.join(root, "prisma", "migrations")
const outDir = path.join(root, "outputs")
const backtick = "`"

// The database to target. Naming it is not a convenience: phpMyAdmin has two
// Import tabs that look identical — one on the server page, one inside a database
// — and importing from the server page fails on the very first statement with
// "#1046 - No database selected", which reads like a problem with the file. A
// `USE` line at the top makes the file work from either tab.
const args = process.argv.slice(2)
const upgradeFlag = args.indexOf("--upgrade-from")
const upgradeFrom = upgradeFlag >= 0 ? args[upgradeFlag + 1] : null
if (upgradeFlag >= 0 && (!upgradeFrom || upgradeFrom.startsWith("-"))) {
  throw new Error("--upgrade-from needs the name of the last migration the database has, e.g. 20260930100000_two_person_counter_refunds_and_payouts")
}
const requested = args.find((arg, index) => arg && !arg.startsWith("-") && index !== upgradeFlag + 1)
if (requested && !/^[A-Za-z0-9_$]+$/.test(requested)) {
  throw new Error(`"${requested}" is not a valid MySQL database name`)
}

// `--reset` prefixes the file with a DROP for every table the schema defines, so a
// single import replaces a database that still holds test data — otherwise the very
// first CREATE fails with "#1050 - Table 'users' already exists". Opt-in, never the
// default: a file whose name does not say "reset" must not delete anything.
const reset = args.includes("--reset")

function stamp() {
  const now = new Date()
  const pad = (value) => String(value).padStart(2, "0")
  return (
    `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}` +
    `-${pad(now.getHours())}${pad(now.getMinutes())}`
  )
}

// Prisma's own diff, so the DDL is whatever the current schema says rather than a
// concatenation of migrations — which would carry every later ALTER of a column
// that was only ever temporary.
function schemaSql() {
  // One command string rather than an args array: `npx` needs a shell on Windows,
  // and Node warns about passing separate args through one. Nothing here is
  // user-supplied, so there is no interpolation to escape.
  return execSync(
    "npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script",
    { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
  )
}

function migrations() {
  return fs
    .readdirSync(migrationsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((name) => {
      const file = path.join(migrationsDir, name, "migration.sql")
      if (!fs.existsSync(file)) throw new Error(`${name} has no migration.sql`)
      return {
        name,
        checksum: crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex"),
      }
    })
}

function quote(value) {
  return `'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`
}

const applied = migrations()
if (applied.length === 0) throw new Error("No migrations found — refusing to write an empty history")

if (upgradeFrom) {
  upgradeFile(upgradeFrom)
  process.exit(0)
}

/**
 * An upgrade for a database in use: only the migrations after `from`, and nothing dropped.
 *
 * phpMyAdmin stops at the first failing statement, and MySQL has no IF outside a stored
 * procedure, so the guards are statements that fail on purpose. A single-row INSERT of NULL
 * into a NOT NULL column fails with #1048 in every sql_mode, strict or not:
 *
 *   - before anything else: the database must have `from` applied and finished, or the
 *     file is for a different database, or one further behind (#1048, nothing changed);
 *   - before each migration: it must not be applied already, so importing the file twice
 *     stops at the first one (#1048, nothing changed).
 *
 * Each migration is then recorded as started, run, and marked finished - the way Prisma
 * records one - so a failure part-way leaves a visibly failed migration, not a silent one.
 */
function upgradeFile(from) {
  const start = applied.findIndex((migration) => migration.name === from)
  if (start < 0) throw new Error(`${from} is not a migration in prisma/migrations`)
  const pending = applied.slice(start + 1)
  if (pending.length === 0) throw new Error(`Nothing to upgrade: ${from} is the newest migration`)

  const guardTable = `${backtick}_upgrade_guard${backtick}`
  const history = `${backtick}_prisma_migrations${backtick}`
  const blocks = pending.map(({ name, checksum }) => {
    const id = crypto.createHash("sha256").update(`upgrade:${name}`).digest("hex")
    const uuid = `${id.slice(0, 8)}-${id.slice(8, 12)}-${id.slice(12, 16)}-${id.slice(16, 20)}-${id.slice(20, 32)}`
    const sql = fs.readFileSync(path.join(migrationsDir, name, "migration.sql"), "utf8").trim()
    return [
      `-- ${name} ${"-".repeat(Math.max(0, 76 - name.length))}`,
      "",
      "-- Stops here (#1048) if this migration is already applied.",
      `INSERT INTO ${guardTable} (${backtick}step${backtick}) VALUES ((SELECT IF(COUNT(*) = 0, ${quote(name)}, NULL) FROM ${history} WHERE ${backtick}migration_name${backtick} = ${quote(name)}));`,
      `INSERT INTO ${history} (${backtick}id${backtick}, ${backtick}checksum${backtick}, ${backtick}finished_at${backtick}, ${backtick}migration_name${backtick}, ${backtick}logs${backtick}, ${backtick}rolled_back_at${backtick}, ${backtick}started_at${backtick}, ${backtick}applied_steps_count${backtick})`,
      `VALUES (${quote(uuid)}, ${quote(checksum)}, NULL, ${quote(name)}, NULL, NULL, NOW(3), 0);`,
      "",
      sql,
      "",
      `UPDATE ${history} SET ${backtick}finished_at${backtick} = NOW(3), ${backtick}applied_steps_count${backtick} = 1 WHERE ${backtick}id${backtick} = ${quote(uuid)};`,
      "",
    ].join("\n")
  })

  const header = [
    "-- DigiSchool-Pro database upgrade",
    "--",
    `-- Generated ${new Date().toISOString()}. For a database whose newest migration is`,
    `--   ${from}`,
    `-- It applies ${pending.length} migration(s) after it, in order, and records each in`,
    "-- _prisma_migrations. It drops nothing and deletes no data.",
    "--",
    "-- Take a backup first (phpMyAdmin > Export). If it stops with #1048 before its first",
    "-- migration, the database is not at the migration above: check with",
    "--   SELECT migration_name FROM _prisma_migrations ORDER BY migration_name DESC LIMIT 1;",
    "-- If it stops with #1048 at a migration, that one is already applied; nothing after",
    "-- it ran. Any other error part-way leaves that migration recorded as not finished.",
    "",
    ...(requested ? [`USE ${backtick}${requested}${backtick};`, ""] : [
      "-- No target database: select it in phpMyAdmin's sidebar and import from its own Import tab.",
      "",
    ]),
    `CREATE TEMPORARY TABLE ${guardTable} (${backtick}step${backtick} VARCHAR(255) NOT NULL);`,
    "",
    "-- Stops here (#1048) unless the database is at the migration named above.",
    `INSERT INTO ${guardTable} (${backtick}step${backtick}) VALUES ((SELECT ${backtick}migration_name${backtick} FROM ${history} WHERE ${backtick}migration_name${backtick} = ${quote(from)} AND ${backtick}finished_at${backtick} IS NOT NULL AND ${backtick}rolled_back_at${backtick} IS NULL));`,
    "",
  ].join("\n")

  fs.mkdirSync(outDir, { recursive: true })
  const outFile = path.join(outDir, `release-upgrade-${requested ?? "db"}-${stamp()}.sql`)
  fs.writeFileSync(outFile, header + blocks.join("\n") + `DROP TEMPORARY TABLE ${guardTable};\n`, "utf8")
  console.log(`\nWrote ${path.relative(root, outFile)}`)
  console.log(`  from ${from}`)
  console.log(`  applies ${pending.length} migration(s): ${pending.map((migration) => migration.name).join(", ")}`)
  console.log("  drops nothing; take a backup first, then import it through phpMyAdmin.")
}

const ddl = schemaSql()
if (!/CREATE TABLE/i.test(ddl)) throw new Error("Prisma produced no CREATE TABLE — refusing to write it")

// Read the table names out of the DDL rather than keeping a second list that could
// fall behind the schema. `_prisma_migrations` is added by hand because Prisma owns
// it and it is not in the datamodel. Naming every table, rather than dropping the
// database, is deliberate: anything else sharing the database is left alone.
const schemaTables = [...ddl.matchAll(/CREATE TABLE `([^`]+)`/g)].map((match) => match[1])
if (schemaTables.length === 0) throw new Error("Could not read any table name out of the DDL")
const dropTargets = [...schemaTables, "_prisma_migrations"]

// UUIDs rather than the migration name, because that is what the column holds and
// what Prisma writes itself.
const historyRows = applied
  .map(
    ({ name, checksum }) =>
      `  (${quote(crypto.randomUUID())}, ${quote(checksum)}, NOW(3), ${quote(name)}, NULL, NULL, NOW(3), 1)`,
  )
  .join(",\n")

const targetBlock = requested
  ? [
      `-- Target database: ${requested}`,
      "--",
      "-- The USE below means this imports correctly from either of phpMyAdmin's",
      "-- Import tabs: the one on the server page or the one inside a database.",
      "",
      `USE ${backtick}${requested}${backtick};`,
    ].join("\n")
  : [
      "-- !! NO TARGET DATABASE",
      "--",
      "-- This file was built without a database name, so it carries no USE statement.",
      "-- In phpMyAdmin you must select the database in the left sidebar first and use",
      "-- the Import tab INSIDE it; importing from the server page fails on the first",
      '-- statement with "#1046 - No database selected".',
      "--",
      "-- Rebuild it with the name to remove that trap:",
      "--   npm run build:release-sql -- your_database_name",
    ].join("\n")

// Foreign keys are switched off for the whole file, so the drop order does not
// matter and no table has to be dropped before its parent.
const dropBlock = reset
  ? [
      "",
      "-- Reset -----------------------------------------------------------------------",
      "--",
      `-- Drops the ${dropTargets.length} tables this schema owns. Everything in them is gone.`,
      "-- Tables belonging to anything else in the same database are untouched, because",
      "-- only the names listed below are dropped.",
      "",
      ...dropTargets.map((table) => `DROP TABLE IF EXISTS ${backtick}${table}${backtick};`),
    ].join("\n")
  : ""

const dataWarning = reset
  ? [
      "-- !! THIS FILE DELETES DATA",
      "--",
      `-- It drops all ${dropTargets.length} tables before recreating them, so importing it over a`,
      "-- database that is in use destroys every row in it. Take a backup first.",
      "--",
      "",
    ].join("\n")
  : [
      "-- It does NOT drop anything. Run it against a database you have just created,",
      "-- or one you have emptied yourself. Over a database that still has the tables it",
      `-- stops on the first statement with "#1050 - Table 'users' already exists"; rebuild`,
      "-- with --reset for a file that clears them first.",
      "",
    ].join("\n")

const header = `-- DigiSchool-Pro release schema
--
-- Generated ${new Date().toISOString()} from prisma/schema.prisma.
-- It creates every table and records all ${applied.length} migrations as already applied,
-- so ${backtick}prisma migrate status${backtick} reports a clean history afterwards.
--
-- It contains no INSERTs other than the migration history: no school, no users,
-- no demo data. Create the super admins afterwards with the "seed" script in
-- Setup Node.js App.
--
${dataWarning}
${targetBlock}

SET FOREIGN_KEY_CHECKS = 0;
${dropBlock}
`

const footer = `
-- Migration history ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ${backtick}_prisma_migrations${backtick} (
  ${backtick}id${backtick} VARCHAR(36) NOT NULL,
  ${backtick}checksum${backtick} VARCHAR(64) NOT NULL,
  ${backtick}finished_at${backtick} DATETIME(3) NULL,
  ${backtick}migration_name${backtick} VARCHAR(255) NOT NULL,
  ${backtick}logs${backtick} TEXT NULL,
  ${backtick}rolled_back_at${backtick} DATETIME(3) NULL,
  ${backtick}started_at${backtick} DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  ${backtick}applied_steps_count${backtick} INTEGER UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (${backtick}id${backtick})
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

INSERT INTO ${backtick}_prisma_migrations${backtick}
  (${backtick}id${backtick}, ${backtick}checksum${backtick}, ${backtick}finished_at${backtick}, ${backtick}migration_name${backtick}, ${backtick}logs${backtick}, ${backtick}rolled_back_at${backtick}, ${backtick}started_at${backtick}, ${backtick}applied_steps_count${backtick})
VALUES
${historyRows};

SET FOREIGN_KEY_CHECKS = 1;
`

fs.mkdirSync(outDir, { recursive: true })
const kind = reset ? "reset" : "schema"
const outFile = path.join(
  outDir,
  requested ? `release-${kind}-${requested}-${stamp()}.sql` : `release-${kind}-${stamp()}.sql`,
)
fs.writeFileSync(outFile, header + "\n" + ddl + footer, "utf8")

const size = (fs.statSync(outFile).size / 1024).toFixed(0)
const tables = (ddl.match(/CREATE TABLE/gi) ?? []).length

console.log(`\nWrote ${path.relative(root, outFile)}  (${size} KB)`)
console.log(`  ${tables} tables`)
console.log(`  ${applied.length} migrations recorded as applied`)
if (reset) console.log(`  DROPS ${dropTargets.length} tables first — THIS FILE DELETES DATA`)

if (requested) {
  console.log(`  targets ${requested} with a USE statement`)
  console.log(`\nImport it through phpMyAdmin from either Import tab.`)
} else {
  console.log(`  NO target database, so no USE statement`)
  console.log(`\nImport it from the Import tab INSIDE the database, or rebuild with:`)
  console.log(`  npm run build:release-sql -- your_database_name`)
}
console.log(`It creates no users — run the "seed" script afterwards for the super admins.`)
