const STATUS_LABEL: Record<string, string> = {
  DRAFT: "Draft",
  PENDING_APPROVAL: "Awaiting approval",
  APPROVED: "Approved",
  PAID: "Paid",
  CANCELLED: "Cancelled",
  PENDING: "Pending",
  EXCLUDED: "Excluded",
}

const MONTH_NAMES = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
]

function periodName(period: string): string {
  const [year, month] = period.split("-")
  const index = Number(month) - 1
  return MONTH_NAMES[index] ? `${MONTH_NAMES[index]} ${year}` : period
}

export async function PayrollListView({ basePath }: { basePath: string }) {
  const runs = await getPayrollRuns()
  if (!runs.success) {
    return <p className="text-destructive">{runs.error}</p>
  }

  const exportTable: ExportTable = {
    columns: ["Period", "Status", "Staff", "Gross", "Deductions", "Net", "Generated By", "Approved By", "Paid By"],
    rows: runs.data.map((run) => [
      periodName(run.period),
      STATUS_LABEL[run.status] ?? run.status,
      String(run.staffCount),
      formatNairaPlain(run.totalGross),
      formatNairaPlain(run.totalDeductions),
      formatNairaPlain(run.totalNet),
      run.generatedByName,
      run.approvedByName ?? "-",
      run.paidByName ?? "-",
    ]),
    csvRows: runs.data.map((run) => [
      run.period,
      run.status,
      String(run.staffCount),
      toCsvAmount(run.totalGross),
      toCsvAmount(run.totalDeductions),
      toCsvAmount(run.totalNet),
      run.generatedByName,
      run.approvedByName ?? "",
      run.paidByName ?? "",
    ]),
  }

  const runColumns: DataTableColumn[] = [
    { label: "Period" },
    { label: "Status" },
    { label: "Staff", align: "right" },
    { label: "Gross", align: "right" },
    { label: "Deductions", align: "right" },
    { label: "Net", align: "right" },
    { label: "Action", printHidden: true },
  ]

  const runRows: DataTableRow[] = runs.data.map((run) => ({
    id: run.id,
    search: `${periodName(run.period)} ${STATUS_LABEL[run.status] ?? run.status}`,
    // Keyed because this array is built on the server and crosses into the client payload,
    // where React checks the elements of a list for keys.
    cells: [
      <span key="period" className="font-medium">
        {periodName(run.period)}
      </span>,
      <Badge key="status" variant="outline">
        {STATUS_LABEL[run.status] ?? run.status}
      </Badge>,
      <span key="staff" className="tabular-nums">
        {run.staffCount}
      </span>,
      <span key="gross" className="whitespace-nowrap tabular-nums">
        {formatNaira(run.totalGross)}
      </span>,
      <span key="deductions" className="whitespace-nowrap tabular-nums">
        {formatNaira(run.totalDeductions)}
      </span>,
      <span key="net" className="whitespace-nowrap font-semibold tabular-nums">
        {formatNaira(run.totalNet)}
      </span>,
      <Button key="open" variant="outline" size="sm" asChild>
        <Link href={`${basePath}/payroll/${run.id}`}>Open</Link>
      </Button>,
    ],
  }))

  return (
    <div className="space-y-6" data-print-document data-print-report>
      <PrintLandscape />
      <BrandedPrintHeader title="Payroll Runs" />
      <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between print:hidden">
        <div>
          <BackButton fallbackHref={basePath} />
          <div className="flex items-center gap-1.5">
            <h1 className="text-3xl font-bold tracking-tight">Payroll</h1>
            <InfoGuide guideKey="hr.payroll" />
          </div>
          <p className="text-muted-foreground">One run per month. Generate, approve, then pay.</p>
        </div>
        <div className="flex flex-wrap gap-2">
          <BrandedReportExport title="Payroll Runs" subtitle="Monthly payroll history" table={exportTable} />
          <Button size="sm" asChild>
            <Link href={`${basePath}/payroll/new`}>Generate Payroll</Link>
          </Button>
        </div>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Payroll Runs</CardTitle>
          <CardDescription>{runs.data.length} {runs.data.length === 1 ? "run" : "runs"}</CardDescription>
        </CardHeader>
        <CardContent>
          <DataTable
            columns={runColumns}
            rows={runRows}
            unit="runs"
            searchPlaceholder="Search by period or status"
            emptyMessage="No payroll yet. Assign salaries first, then generate a month."
          />
        </CardContent>
      </Card>
    </div>
  )
}

export async function PayrollRunView({
  basePath,
  runId,
  canManage,
}: {
  basePath: string
  runId: string
  canManage: boolean
}) {
  // Expenditure categories come along because paying a run books it as expenditure, and the
  // pay dialog has to offer somewhere for it to land.
  const [result, setup, expenditure] = await Promise.all([
    getPayrollRun(runId),
    getHrSetupData(),
    getExpenditureSetupData(),
  ])
  if (!result.success) notFound()
  if (!setup.success) {
    return <p className="text-destructive">{setup.error}</p>
  }

  const run = result.data
  const categories = expenditure.success
    ? expenditure.data.categories.map((category) => ({
        id: category.id,
        name: category.name,
        isActive: category.isActive,
      }))
    : []

  const exportTable: ExportTable = {
    columns: ["Payslip No", "Staff No", "Name", "Department", "Base", "Allowances", "Deductions", "Gross", "Net", "Bank", "Account", "Status"],
    rows: run.items.map((item) => [
      item.payslipNo,
      item.staffNo,
      item.name,
      item.department ?? "-",
      formatNairaPlain(item.baseSalary),
      formatNairaPlain(item.totalAllowances),
      formatNairaPlain(item.totalDeductions),
      formatNairaPlain(item.grossPay),
      formatNairaPlain(item.netPay),
      item.bankName ?? "-",
      item.accountNumber ?? "-",
      STATUS_LABEL[item.status] ?? item.status,
    ]),
    csvRows: run.items.map((item) => [
      item.payslipNo,
      item.staffNo,
      item.name,
      item.department ?? "",
      toCsvAmount(item.baseSalary),
      toCsvAmount(item.totalAllowances),
      toCsvAmount(item.totalDeductions),
      toCsvAmount(item.grossPay),
      toCsvAmount(item.netPay),
      item.bankName ?? "",
      item.accountNumber ?? "",
      item.status,
    ]),
  }

  const itemColumns: DataTableColumn[] = [
    { label: "Staff" },
    { label: "Base", align: "right" },
    { label: "Allowances", align: "right" },
    { label: "Deductions", align: "right" },
    { label: "Net Pay", align: "right" },
    { label: "Bank" },
    { label: "Status" },
    { label: "Action", printHidden: true },
  ]

  const itemRows: DataTableRow[] = run.items.map((item) => ({
    id: item.id,
    search: [
      item.name,
      item.staffNo,
      item.department ?? "",
      item.bankName ?? "",
      item.accountNumber ?? "",
      STATUS_LABEL[item.status] ?? item.status,
    ].join(" "),
    // Keyed because this array is built on the server and crosses into the client payload,
    // where React checks the elements of a list for keys.
    cells: [
      <div key="staff" className="min-w-0">
        <div className="font-medium">{item.name}</div>
        <div className="text-xs text-muted-foreground">
          {item.staffNo}
          {item.department ? ` · ${item.department}` : ""}
          {item.proratedDays ? ` · ${item.proratedDays}/${item.daysInMonth} days` : ""}
        </div>
      </div>,
      <span key="base" className="whitespace-nowrap tabular-nums">
        {formatNaira(item.baseSalary)}
      </span>,
      <span key="allowances" className="whitespace-nowrap tabular-nums">
        {formatNaira(item.totalAllowances)}
      </span>,
      <span key="deductions" className="whitespace-nowrap tabular-nums">
        {formatNaira(item.totalDeductions)}
      </span>,
      <span key="net" className="whitespace-nowrap font-semibold tabular-nums">
        {formatNaira(item.netPay)}
      </span>,
      item.bankName ? (
        <div key="bank" className="min-w-0">
          <div className="truncate">{item.bankName}</div>
          <div className="text-xs text-muted-foreground">
            {item.accountNumber ?? "No account number"}
          </div>
        </div>
      ) : (
        <span key="bank" className="text-destructive">
          No bank details
        </span>
      ),
      <span key="status">{STATUS_LABEL[item.status] ?? item.status}</span>,
      <Button key="open" variant="outline" size="sm" asChild>
        <Link href={`${basePath}/payslips/${item.id}`}>Payslip</Link>
      </Button>,
    ],
  }))

  return (
    <div className="space-y-6" data-print-document data-print-report>
      <PrintLandscape />
      <BrandedPrintHeader title="Monthly Salary Schedule" reference={periodName(run.period)} />
      <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between print:hidden">
        <div>
          <div className="flex items-center gap-3">
            <BackButton fallbackHref={`${basePath}/payroll`} />
            <div className="flex items-center gap-1.5">
              <h1 className="text-3xl font-bold tracking-tight">{periodName(run.period)}</h1>
              <InfoGuide guideKey="hr.payrollRun" />
            </div>
            <Badge variant="outline">{STATUS_LABEL[run.status] ?? run.status}</Badge>
          </div>
          <p className="text-muted-foreground">
            {run.items.length} staff · {formatNaira(run.totals.net)} net
            {run.sessionName ? ` · ${run.sessionName}` : ""}
          </p>
        </div>
        <div className="flex flex-wrap gap-2">
          <BrandedReportExport
            title={`Payroll ${periodName(run.period)}`}
            subtitle={`Monthly salary schedule · ${STATUS_LABEL[run.status] ?? run.status}`}
            table={exportTable}
          />
          <PayrollWorkflowActions
            basePath={basePath}
            runId={run.id}
            status={run.status}
            canManage={canManage}
            accounts={setup.data.accounts}
            categories={categories}
            defaultAccountId={setup.data.config.defaultAccountId}
            defaultMethod={setup.data.config.defaultPaymentMethod}
          />
        </div>
      </div>

      {run.decisionReason && (
        <div className="rounded-md border border-dashed p-4">
          <p className="font-medium">{run.status === "CANCELLED" ? "Cancelled" : run.status === "REVERSED" ? "Reversal" : "Note"}</p>
          <p className="text-sm text-muted-foreground">{run.decisionReason}</p>
        </div>
      )}

      <div className="grid gap-4 md:grid-cols-5">
        <Figure label="Base" value={run.totals.base} />
        <Figure label="Allowances" value={run.totals.allowances} />
        <Figure label="Deductions" value={run.totals.deductions} />
        <Figure label="Gross" value={run.totals.gross} />
        <Figure label="Net" value={run.totals.net} strong />
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Approval Trail</CardTitle>
          <CardDescription>Who prepared it, who allowed it, who released the money.</CardDescription>
        </CardHeader>
        <CardContent className="grid gap-4 sm:grid-cols-3">
          <Step label="Generated" who={run.generatedByName} when={null} done />
          <Step label="Approved" who={run.approvedByName} when={run.approvedAt} done={Boolean(run.approvedByName)} />
          <Step label="Paid" who={run.paidByName} when={run.paidAt} done={Boolean(run.paidByName)} />
          {run.expenseVoucherNo && (
            <div className="sm:col-span-3 text-sm text-muted-foreground">
              Booked as expenditure voucher <span className="font-medium">{run.expenseVoucherNo}</span>, so it appears
              in the budget summary like any other spending.
            </div>
          )}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>Salary Schedule</CardTitle>
          <CardDescription>One line per staff member. Open a payslip for the full breakdown.</CardDescription>
        </CardHeader>
        <CardContent>
          <DataTable
            columns={itemColumns}
            rows={itemRows}
            unit="staff"
            searchPlaceholder="Search staff, number, department or bank"
            emptyMessage="This run has no salary lines."
          />
        </CardContent>
      </Card>
    </div>
  )
}

export async function PayslipView({ basePath, itemId }: { basePath: string; itemId: string }) {
  const result = await getPayslip(itemId)
  if (!result.success) notFound()

  const payslip = result.data

  const document: PrintableDocument = {
    title: "Payslip",
    reference: payslip.payslipNo,
    schoolName: payslip.school.name,
    schoolCode: payslip.school.code,
    fields: [
      { label: "Staff", value: `${payslip.staff.name} (${payslip.staff.staffNo})` },
      { label: "Department", value: payslip.staff.department ?? "-" },
      { label: "Job Title", value: payslip.staff.jobTitle ?? "-" },
      { label: "Period", value: periodName(payslip.period) },
      { label: "Basic Salary", value: formatNairaPlain(payslip.baseSalary) },
      { label: "Paid On", value: payslip.paidAt ? new Date(payslip.paidAt).toLocaleDateString() : "Not yet paid" },
    ],
    table: {
      caption: "Breakdown",
      columns: ["Item", "Type", "Amount"],
      rows: [
        ["Basic salary", "Earning", formatNairaPlain(payslip.baseSalary)],
        ...payslip.allowances.map((line) => [line.label, "Allowance", formatNairaPlain(line.amount)]),
        ...payslip.deductions.map((line) => [line.label, "Deduction", `-${formatNairaPlain(line.amount)}`]),
      ],
    },
    totals: [
      { label: "Gross pay", value: formatNairaPlain(payslip.grossPay) },
      { label: "Total deductions", value: formatNairaPlain(payslip.totalDeductions) },
      { label: "Net pay", value: formatNairaPlain(payslip.netPay) },
    ],
  }

  return (
    <div
      className="mx-auto max-w-3xl space-y-6 print:mx-0 print:max-w-none print:space-y-0"
      data-print-page
    >
      <div className="flex items-start justify-between gap-4 print:hidden">
        <div>
          <BackButton fallbackHref={`${basePath}/payroll`} />
          <div className="flex items-center gap-1.5">
            <h1 className="text-3xl font-bold tracking-tight">Payslip</h1>
            <InfoGuide guideKey="hr.payslip" />
          </div>
          <p className="text-muted-foreground">{payslip.payslipNo} · {periodName(payslip.period)}</p>
        </div>
        <div className="flex gap-2">
          <PrintButton label="Print Payslip" />
          <BrandedDocumentDownload document={document} label="Download PDF" />
        </div>
      </div>

      <Card data-print-document className="print:rounded-none print:border-0 print:shadow-none">
        <BrandedPrintHeader title="Payslip" reference={`${payslip.payslipNo} · ${periodName(payslip.period)}`} />
        <CardHeader className="border-b print:px-0 print:pb-4">
          <div className="flex items-start justify-between gap-4">
            {/* Suppressed on paper: BrandedPrintHeader above carries the letterhead there. */}
            <div className="print:hidden">
              <CardTitle>{payslip.school.name}</CardTitle>
              <p className="text-sm text-muted-foreground">{payslip.school.code}</p>
            </div>
            <div className="text-right print:w-full">
              <p className="text-sm text-muted-foreground">Net Pay</p>
              <p className="text-2xl font-bold">{formatNaira(payslip.netPay)}</p>
              <Badge variant="outline" className="mt-1">{STATUS_LABEL[payslip.status] ?? payslip.status}</Badge>
            </div>
          </div>
        </CardHeader>
        <CardContent className="space-y-6 pt-6">
          <div className="grid gap-4 sm:grid-cols-2">
            <Info label="Staff" value={`${payslip.staff.name} (${payslip.staff.staffNo})`} />
            <Info label="Period" value={periodName(payslip.period)} />
            <Info label="Department" value={payslip.staff.department ?? "—"} />
            <Info label="Job title" value={payslip.staff.jobTitle ?? "—"} />
            <Info
              label="Bank"
              value={
                payslip.staff.bankName
                  ? `${payslip.staff.bankName} · ${payslip.staff.accountNumber ?? "no account number"}`
                  : "—"
              }
            />
            <Info label="Paid on" value={payslip.paidAt ? new Date(payslip.paidAt).toLocaleDateString() : "Not yet paid"} />
          </div>

          {payslip.proratedDays && (
            <div className="rounded-md border border-dashed p-3 text-sm text-muted-foreground">
              Paid for {payslip.proratedDays} of {payslip.daysInMonth} days — a part month.
            </div>
          )}

          <div className="grid gap-6 sm:grid-cols-2">
            <div>
              <h2 className="mb-3 font-semibold">Earnings</h2>
              <div className="space-y-2">
                <Line label="Basic salary" amount={payslip.baseSalary} />
                {payslip.allowances.map((line, index) => (
                  <Line key={`${line.label}-${index}`} label={line.label} amount={line.amount} />
                ))}
                <div className="flex justify-between border-t pt-2 font-semibold">
                  <span>Gross pay</span>
                  <span>{formatNaira(payslip.grossPay)}</span>
                </div>
              </div>
            </div>

            <div>
              <h2 className="mb-3 font-semibold">Deductions</h2>
              <div className="space-y-2">
                {payslip.deductions.length > 0 ? (
                  payslip.deductions.map((line, index) => (
                    <Line key={`${line.label}-${index}`} label={line.label} amount={line.amount} />
                  ))
                ) : (
                  <p className="text-sm text-muted-foreground">No deductions.</p>
                )}
                <div className="flex justify-between border-t pt-2 font-semibold">
                  <span>Total deductions</span>
                  <span>{formatNaira(payslip.totalDeductions)}</span>
                </div>
              </div>
            </div>
          </div>

          <div className="rounded-md bg-muted p-4 text-right">
            <p className="text-sm text-muted-foreground">Net Pay</p>
            <p className="text-xl font-bold">{formatNaira(payslip.netPay)}</p>
          </div>

          {payslip.payslipNote && (
            <p className="text-sm text-muted-foreground">{payslip.payslipNote}</p>
          )}
        </CardContent>
      </Card>
    </div>
  )
}

function Figure({ label, value, strong }: { label: string; value: string; strong?: boolean }) {
  return (
    <Card>
      <CardHeader className="pb-2"><CardTitle className="text-sm">{label}</CardTitle></CardHeader>
      <CardContent className={strong ? "text-2xl font-bold" : "text-xl font-semibold"}>
        {formatNaira(value, { kobo: false })}
      </CardContent>
    </Card>
  )
}

function Info({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <p className="text-sm text-muted-foreground">{label}</p>
      <p className="font-medium">{value}</p>
    </div>
  )
}

function Line({ label, amount }: { label: string; amount: string }) {
  return (
    <div className="flex justify-between border-b pb-2 last:border-0">
      <span>{label}</span>
      <span className="font-medium">{formatNaira(amount)}</span>
    </div>
  )
}

function Step({
  label,
  who,
  when,
  done,
}: {
  label: string
  who: string | null
  when: string | null
  done: boolean
}) {
  return (
    <div className="flex gap-3">
      <div className={`mt-1 h-3 w-3 shrink-0 rounded-full ${done ? "bg-primary" : "border-2 border-muted-foreground/40"}`} />
      <div>
        <p className="font-medium">{label}</p>
        <p className="text-sm text-muted-foreground">
          {who ?? "Not yet"}
          {when ? ` · ${new Date(when).toLocaleString()}` : ""}
        </p>
      </div>
    </div>
  )
}
