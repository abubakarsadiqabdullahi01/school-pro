/**
 * A whole class's results for a whole session, shaped for the existing report-card PDF.
 *
 * The termly card is generated by `lib/pdf/student-report-card-generator.tsx`, and the
 * sessional one is the same generator with five column headers renamed. That is deliberate:
 * two generators would be two layouts, and the second would drift from the first the moment
 * either was touched. So this produces the same `StudentResult` shape the termly path
 * produces, with the term columns carrying terms instead of continuous assessments:
 *
 *     termly   1st CA   2nd CA   3rd CA   Exam    Total
 *     session  1st Term 2nd Term 3rd Term Total   Average
 *
 * Positions and class statistics are computed across the session rather than copied from
 * any one term, because a child who was second in first term and tenth in third term is
 * neither over the year.
 *
 * Nothing here is gated on fees. Staff always see marks; the portal applies the withholding
 * rule itself before it shows or prints anything.
 */

export type SessionSubjectResult = {
  ca1: number | null
  ca2: number | null
  ca3: number | null
  exam: number | null
  score: number | null
  grade: string | null
  remark: string | null
  position: number | null
  outOf: number
  lowest: number
  highest: number
  average: number
}

export type SessionStudentResult = {
  studentId: string
  studentName: string
  admissionNo: string
  gender: string | null
  passportUrl: string | null
  subjects: Record<string, SessionSubjectResult>
  totalScore: number
  averageScore: number
  grade: string | null
  remark: string
  position: number
  /** How many of the session's terms this learner has any released mark in. */
  termsCounted: number
  /**
   * The end-of-session outcome, once a principal has approved it.
   *
   * PENDING whenever nothing has been approved - which is the honest answer, and the
   * reason the card prints nothing rather than assuming a promotion nobody has agreed to.
   */
  annualDecision: AnnualDecision
  /** The principal's own words. Empty until they write them. */
  principalComment: string
}

export type SessionClassReport = {
  /**
   * `endDate` and `nextStartDate` fill the card's "Term Ends" and "Next Term Begins" lines,
   * which the generator requires and refuses to invent. On a sessional card they carry the
   * session's own end and the start of the session after it.
   */
  session: { id: string; name: string; endDate: string; nextStartDate: string }
  className: string
  /** Whoever took the class, for the sheet's teacher line. */
  teacherName: string
  /** The session's terms in calendar order — the three score columns, in order. */
  terms: Array<{ id: string; name: string }>
  subjects: Array<{ id: string; name: string; code: string }>
  students: SessionStudentResult[]
  statistics: {
    highestTotal: number
    lowestTotal: number
    classAverage: number
    subjectHighest: Record<string, number>
    subjectLowest: Record<string, number>
    subjectAverage: Record<string, number>
  }
  gradingSystem: { passMark: number; levels: Array<{ minScore: number; maxScore: number; grade: string; remark: string }> }
}

export async function buildSessionClassReport(
  classId: string,
  sessionId: string,
  schoolId: string,
): Promise<SessionClassReport | null> {
  const [classRow, session, grading] = await Promise.all([
    prisma.class.findUnique({ where: { id: classId }, select: { name: true, schoolId: true } }),
    prisma.session.findUnique({
      where: { id: sessionId },
      select: { id: true, name: true, schoolId: true, startDate: true, endDate: true },
    }),
    loadGradingSystem(schoolId),
  ])

  if (!classRow || !session) return null
  if (classRow.schoolId !== schoolId || session.schoolId !== schoolId) return null

  // Every class-term this class ran in this session, in calendar order. These are the three
  // score columns, and their order is the order they are printed in.
  const classTerms = await prisma.classTerm.findMany({
    where: { classId, term: { sessionId } },
    orderBy: { term: { startDate: "asc" } },
    select: {
      id: true,
      termId: true,
      term: { select: { id: true, name: true } },
      classSubjects: { select: { subject: { select: { id: true, name: true, code: true } } } },
      teachers: {
        take: 1,
        select: { teacher: { select: { user: { select: { firstName: true, lastName: true } } } } },
      },
      students: {
        select: {
          student: {
            select: {
              id: true,
              admissionNo: true,
              user: { select: { firstName: true, lastName: true, gender: true, avatarUrl: true } },
            },
          },
        },
      },
    },
  })

  if (classTerms.length === 0) return null

  // The session that follows this one, for the "Next Term Begins" line. When this is the
  // newest session there is nothing to name, so the session's own end date stands in rather
  // than leaving the generator a blank it refuses to accept.
  const nextSession = await prisma.session.findFirst({
    where: { schoolId, startDate: { gt: session.endDate } },
    orderBy: { startDate: "asc" },
    select: {
      startDate: true,
      // "Next Term Begins" means the next session's FIRST TERM, which is the date a school
      // actually puts on a report card. A session's own start date can be an administrative
      // date weeks earlier, and telling a family to bring their child back then is wrong.
      terms: { orderBy: { startDate: "asc" }, take: 1, select: { startDate: true } },
    },
  })

  // The first term's date when the next session has terms set up, the session's own start
  // when it does not yet, and nothing at all when there is no next session.
  const nextStart = nextSession?.terms[0]?.startDate ?? nextSession?.startDate ?? null

  const teacherUser = classTerms.find((row) => row.teachers.length > 0)?.teachers[0]?.teacher.user
  const teacherName = teacherUser ? `${teacherUser.firstName} ${teacherUser.lastName}` : null

  const terms = classTerms.map((row) => ({ id: row.term.id, name: row.term.name }))
  const termIndex = new Map(terms.map((term, index) => [term.id, index]))

  // Subjects the class offered at any point in the session, so a subject dropped after
  // first term still shows the marks it earned rather than vanishing from the record.
  const subjectMap = new Map<string, { id: string; name: string; code: string }>()
  for (const classTerm of classTerms) {
    for (const row of classTerm.classSubjects) subjectMap.set(row.subject.id, row.subject)
  }
  const subjects = [...subjectMap.values()].sort((a, b) => a.name.localeCompare(b.name))

  const studentMap = new Map<
    string,
    { id: string; admissionNo: string; firstName: string; lastName: string; gender: string | null; avatarUrl: string | null }
  >()
  for (const classTerm of classTerms) {
    for (const row of classTerm.students) {
      studentMap.set(row.student.id, {
        id: row.student.id,
        admissionNo: row.student.admissionNo,
        firstName: row.student.user.firstName,
        lastName: row.student.user.lastName,
        gender: row.student.user.gender,
        avatarUrl: row.student.user.avatarUrl,
      })
    }
  }

  // Only APPROVED decisions. An unapproved row is work in progress by an exams officer,
  // and this same builder feeds the parent and student portals - a family must not see
  // "Repeat" before the principal has signed it off.
  const decisions = await prisma.annualResultDecision.findMany({
    where: {
      studentId: { in: [...studentMap.keys()] },
      sessionId,
      approvedAt: { not: null },
    },
    select: { studentId: true, decision: true, principalComment: true },
  })
  const decisionByStudent = new Map(decisions.map((row) => [row.studentId, row]))

  const assessments = await prisma.assessment.findMany({
    where: {
      studentId: { in: [...studentMap.keys()] },
      termId: { in: terms.map((term) => term.id) },
      ...PUBLISHED_ONLY,
    },
    select: {
      studentId: true,
      subjectId: true,
      termId: true,
      ca1: true,
      ca2: true,
      ca3: true,
      exam: true,
      isAbsent: true,
      isExempt: true,
    },
  })

  // studentId -> subjectId -> [term0, term1, term2]
  const marks = new Map<string, Map<string, Array<number | null>>>()
  for (const row of assessments) {
    if (row.isAbsent || row.isExempt) continue
    const index = termIndex.get(row.termId)
    if (index === undefined) continue

    const total = subjectTotal(row)
    if (total === null) continue

    if (!marks.has(row.studentId)) marks.set(row.studentId, new Map())
    const bySubject = marks.get(row.studentId)!
    if (!bySubject.has(row.subjectId)) bySubject.set(row.subjectId, terms.map(() => null))
    bySubject.get(row.subjectId)![index] = total
  }

  // Each learner's session average per subject, before positions are worked out.
  type Draft = {
    student: (typeof studentMap extends Map<string, infer V> ? V : never)
    perSubject: Map<string, { termScores: Array<number | null>; total: number; average: number }>
  }

  const drafts: Draft[] = []
  for (const student of studentMap.values()) {
    const bySubject = marks.get(student.id) ?? new Map<string, Array<number | null>>()
    const perSubject = new Map<string, { termScores: Array<number | null>; total: number; average: number }>()

    for (const subject of subjects) {
      const termScores = bySubject.get(subject.id) ?? terms.map(() => null)
      const sat = termScores.filter((score): score is number => score !== null)
      if (sat.length === 0) continue

      const total = sat.reduce((sum, score) => sum + score, 0)
      perSubject.set(subject.id, { termScores, total, average: total / sat.length })
    }

    drafts.push({ student, perSubject })
  }

  // Subject statistics across the class, on session averages.
  const subjectHighest: Record<string, number> = {}
  const subjectLowest: Record<string, number> = {}
  const subjectAverage: Record<string, number> = {}
  const subjectRanking = new Map<string, Array<{ studentId: string; average: number }>>()

  for (const subject of subjects) {
    const scores = drafts
      .map((draft) => ({ studentId: draft.student.id, average: draft.perSubject.get(subject.id)?.average }))
      .filter((row): row is { studentId: string; average: number } => row.average !== undefined)

    if (scores.length === 0) {
      subjectHighest[subject.id] = 0
      subjectLowest[subject.id] = 0
      subjectAverage[subject.id] = 0
      subjectRanking.set(subject.id, [])
      continue
    }

    const values = scores.map((row) => row.average)
    subjectHighest[subject.id] = Math.max(...values)
    subjectLowest[subject.id] = Math.min(...values)
    subjectAverage[subject.id] = values.reduce((sum, value) => sum + value, 0) / values.length
    subjectRanking.set(
      subject.id,
      [...scores].sort((a, b) => b.average - a.average),
    )
  }

  // Overall ranking, on the average of each learner's subject averages.
  const overall = drafts
    .map((draft) => {
      const averages = [...draft.perSubject.values()].map((row) => row.average)
      // The sum of the subject averages — the very numbers the subject columns print — so
      // Total and Average agree on the same row, and two learners are comparable even when
      // one sat two terms and the other three. Summing raw term marks did neither.
      const totalScore = averages.reduce((sum, value) => sum + value, 0)
      const averageScore =
        averages.length === 0 ? 0 : averages.reduce((sum, value) => sum + value, 0) / averages.length
      return { studentId: draft.student.id, totalScore, averageScore }
    })
    .sort((a, b) => b.averageScore - a.averageScore)

  const overallPosition = new Map(overall.map((row, index) => [row.studentId, index + 1]))
  const overallById = new Map(overall.map((row) => [row.studentId, row]))

  const students: SessionStudentResult[] = drafts.map((draft) => {
    const subjectResults: Record<string, SessionSubjectResult> = {}

    for (const subject of subjects) {
      const row = draft.perSubject.get(subject.id)
      if (!row) continue

      const ranking = subjectRanking.get(subject.id) ?? []
      const position = ranking.findIndex((entry) => entry.studentId === draft.student.id)
      const resolved = resolveGrade(Math.round(row.average), grading)

      subjectResults[subject.id] = {
        // The three term columns, then the session total, then the session average. Same
        // five columns the termly card prints, carrying different things.
        ca1: row.termScores[0] ?? null,
        ca2: row.termScores[1] ?? null,
        ca3: row.termScores[2] ?? null,
        exam: row.total,
        score: Math.round(row.average),
        grade: resolved.grade,
        remark: resolved.remark,
        position: position >= 0 ? position + 1 : null,
        outOf: ranking.length,
        lowest: subjectLowest[subject.id] ?? 0,
        highest: subjectHighest[subject.id] ?? 0,
        average: subjectAverage[subject.id] ?? 0,
      }
    }

    const totals = overallById.get(draft.student.id)!
    const resolved = resolveGrade(Math.round(totals.averageScore), grading)
    const termsCounted = new Set(
      [...draft.perSubject.values()].flatMap((row) =>
        row.termScores.map((score, index) => (score === null ? null : index)),
      ),
    )
    termsCounted.delete(null)

    return {
      studentId: draft.student.id,
      studentName: `${draft.student.firstName} ${draft.student.lastName}`,
      admissionNo: draft.student.admissionNo,
      gender: draft.student.gender,
      passportUrl: draft.student.avatarUrl,
      subjects: subjectResults,
      totalScore: Math.round(totals.totalScore),
      averageScore: Math.round(totals.averageScore),
      grade: resolved.grade,
      remark: resolved.remark ?? "",
      position: overallPosition.get(draft.student.id) ?? 0,
      termsCounted: termsCounted.size,
      annualDecision: (decisionByStudent.get(draft.student.id)?.decision ?? "PENDING") as AnnualDecision,
      principalComment: decisionByStudent.get(draft.student.id)?.principalComment ?? "",
    }
  })

  students.sort((a, b) => a.position - b.position)

  const totalsForStats = overall.map((row) => row.averageScore).filter((value) => value > 0)

  return {
    session: {
      id: session.id,
      name: session.name,
      endDate: session.endDate.toISOString(),
      // Empty when the school has not created the next session yet. Repeating the session's
      // own end date here printed "Term Ends" and "Next Term Begins" as the same day, which
      // reads as a bug on a document a parent keeps.
      nextStartDate: nextStart?.toISOString() ?? "",
    },
    className: classRow.name,
    teacherName: teacherName ?? "Not Assigned",
    terms,
    subjects,
    students,
    statistics: {
      highestTotal: totalsForStats.length === 0 ? 0 : Math.max(...totalsForStats),
      lowestTotal: totalsForStats.length === 0 ? 0 : Math.min(...totalsForStats),
      classAverage:
        totalsForStats.length === 0
          ? 0
          : totalsForStats.reduce((sum, value) => sum + value, 0) / totalsForStats.length,
      subjectHighest,
      subjectLowest,
      subjectAverage,
    },
    gradingSystem: grading ?? { passMark: 40, levels: [] },
  }
}

export type SessionReportForStudent = {
  report: SessionClassReport
  student: SessionStudentResult
  school: {
    schoolName: string
    schoolCode: string
    schoolAddress: string
    schoolPhone: string
    schoolEmail: string
    schoolLogo: string | null
  }
}

/**
 * One learner's sessional card, with the class context the card prints around it.
 *
 * The class is resolved from the learner's own enrolments rather than passed in, because a
 * learner who moved class mid-session has more than one, and the one their sessional report
 * belongs to is the last one they sat in.
 */
export async function buildSessionReportForStudent(
  studentId: string,
  sessionId: string,
  schoolId: string,
): Promise<SessionReportForStudent | null> {
  const enrolment = await prisma.studentClassTerm.findFirst({
    where: { studentId, classTerm: { term: { sessionId } } },
    orderBy: { classTerm: { term: { startDate: "desc" } } },
    select: { classTerm: { select: { classId: true } } },
  })
  if (!enrolment) return null

  const [report, school] = await Promise.all([
    buildSessionClassReport(enrolment.classTerm.classId, sessionId, schoolId),
    prisma.school.findUnique({
      where: { id: schoolId },
      select: { name: true, code: true, address: true, phone: true, email: true, logoUrl: true },
    }),
  ])

  if (!report || !school) return null

  const student = report.students.find((row) => row.studentId === studentId)
  if (!student) return null

  return {
    report,
    student,
    school: {
      schoolName: school.name,
      schoolCode: school.code,
      schoolAddress: school.address ?? "",
      schoolPhone: school.phone ?? "",
      schoolEmail: school.email ?? "",
      schoolLogo: school.logoUrl,
    },
  }
}
